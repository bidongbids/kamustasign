"""
Per-sign 3-star reference for practice stars -> src/data/starReference.json.

Stars show accuracy relative to the model, per sign: a student's best
confidence on a sign divided by what the deployed model typically gives a
CORRECTLY made attempt of that sign ("confidence when right" in the
diagnostics). So a sign the model is shaky on (say 0.60 when right) isn't
capped at 1.8 stars, and an easy one (0.97) still needs a clean attempt.

Sources (re-run them after a retrain, then this):
  ASL letters  models/diagnostics/letters_per_class.csv  signers_conf_when_right
               (10 people the model never saw - closer to a student than the
               held-out split, where nearly everything is ~1.0)
  ASL words    models/diagnostics/asl_per_word.csv       conf_when_right
  FSL words    models/diagnostics/fsl-105_per_word.csv   conf_when_right

A sign the model never got right in its test set has no figure; it gets its
group's median. Every reference is clamped to [MIN_REF, 1]: a word right
only a couple of times at ~0.2 would otherwise make 3 stars trivial.

  cd ml
  python scripts/letter_model_diagnostics.py
  python scripts/word_model_diagnostics.py
  python scripts/export_star_reference.py
"""

import os
import csv
import json
import statistics

ML_DIR = os.path.join(os.path.dirname(__file__), "..")
DIAG = os.path.join(ML_DIR, "models", "diagnostics")
OUT = os.path.join(ML_DIR, "..", "src", "data", "starReference.json")
MIN_REF = 0.40  # = the translator's MIN_CONFIDENCE display gate

SOURCES = [
    ("asl", "letters", "letters_per_class.csv", "letter", "signers_conf_when_right"),
    ("asl", "words", "asl_per_word.csv", "word", "conf_when_right"),
    ("fsl", "words", "fsl-105_per_word.csv", "word", "conf_when_right"),
]


def read(path, key_col, conf_col):
    out = {}
    with open(path, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            v = r.get(conf_col, "")
            try:
                v = float(v)
            except ValueError:
                v = float("nan")
            out[r[key_col]] = v
    return out


def main():
    result = {"_note": "Generated by ml/scripts/export_star_reference.py - do not edit by hand."}
    for lang, group, fname, key_col, conf_col in SOURCES:
        raw = read(os.path.join(DIAG, fname), key_col, conf_col)
        if group == "letters":
            raw = {k: v for k, v in raw.items() if len(k) == 1}  # not del/space
        known = [v for v in raw.values() if v == v]
        if not known:
            raise SystemExit(f"{fname}: no {conf_col} values - re-run the diagnostics script")
        median = statistics.median(known)
        refs, fallback = {}, []
        for sign, v in raw.items():
            if v != v:
                fallback.append(sign)
                v = median
            refs[sign] = round(min(1.0, max(MIN_REF, v)), 3)
        result.setdefault(lang, {})[group] = {"_default": round(min(1.0, max(MIN_REF, median)), 3), **refs}
        print(f"{lang} {group}: {len(refs)} signs, median {median:.2f}, "
              f"{sum(1 for v in raw.values() if v == v and v < MIN_REF)} clamped up to {MIN_REF}, "
              f"{len(fallback)} without a figure -> median {fallback[:8]}")
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"wrote {os.path.abspath(OUT)}")


if __name__ == "__main__":
    main()
