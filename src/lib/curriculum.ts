// src/lib/curriculum.ts
// The classroom's fixed learning plan, and the single source of truth for it
// (see docs/CLASSROOM_REDESIGN.md). Nothing here lives in the database: the sign
// lists are read from the label_classes.json each deployed model ships with,
// so the plan can never promise a lesson the app cannot grade, and a model's
// vocabulary changing never needs a seed migration. lesson_progress only
// stores what a student has done; every total and percentage is computed here
// from these lists, so the student, teacher and admin views can't disagree.
import letterClasses from "../../public/model/label_classes.json";
import numberClasses from "../../public/number-model/label_classes.json";
import fslLetterClasses from "../../public/fsl-letter-model/label_classes.json";
import fslNumberClasses from "../../public/fsl-number-model/label_classes.json";
import aslWordClasses from "../../public/word-model/label_classes.json";
import fslWordClasses from "../../public/fsl-model/label_classes.json";
// Reliability order for Words, generated by
// ml/scripts/export_word_practice_order.py from the deployed ensembles'
// held-out per-word accuracy. Since 2026-11-04 it no longer orders the lists
// (they are alphabetical); it only picks a class plan's starter words.
import wordPracticeOrder from "../data/wordPracticeOrder.json";
import { signName } from "./signNames";

export type SignLanguage = "asl" | "fsl";
export type SignGroup = "letters" | "numbers" | "words";

export type GroupDefinition = {
  group: SignGroup;
  label: string;
  signs: string[];
  /** False when no trained model can grade this group yet. */
  available: boolean;
  /** Shown in place of the lesson grid when the group is unavailable. */
  unavailableNote?: string;
};

export type LanguageDefinition = {
  language: SignLanguage;
  label: string;
  groups: GroupDefinition[];
};

// ---- progress rules ----
// Stated in the UI (see PROGRESS_RULES_TEXT) - an invisible rule feels like a bug.

/** A practice attempt passes when the target is recognised at this confidence (0-1). */
export const PASS_CONFIDENCE = 0.8;
/**
 * Counted passes before a sign counts as mastered. One: the first pass learns
 * the sign, and the stars (starReference.ts) show how well it was made.
 */
export const MASTERY_PASSES = 1;
/**
 * Letters/Numbers classify every frame (~30 fps), so one frame of agreement is
 * nearly free. The target must stay recognised at PASS_CONFIDENCE this long.
 */
export const LIVE_PASS_HOLD_MS = 500;

export const PROGRESS_RULES_TEXT =
  `Attempted: practiced at least once. ` +
  `Passed: recognised as the target sign at ${Math.round(PASS_CONFIDENCE * 100)}% confidence or more ` +
  `(letters and numbers must hold it for ${LIVE_PASS_HOLD_MS / 1000}s). ` +
  `Mastered: passed once. ` +
  `Stars: the best attempt compared with what the model gives a correctly made sign of that kind ` +
  `(3 stars = as good as a typical correct attempt), in quarter steps; they don't decide mastery.`;

export const OVERALL_CAPTION = "average across groups";

// ---- sign lists ----

/**
 * A word model trained with an "unknown sign" class (train_word_classifier.py
 * --unknown) has this label too. It's never a lesson; when it wins a
 * prediction, the screens treat it as "no sign".
 */
export const UNKNOWN_SIGN_LABEL = "__unknown__";
const notUnknown = (c: string) => c !== UNKNOWN_SIGN_LABEL;

// The letters model also has "del"/"space" (and some builds "nothing"): those
// are fingerspelling UI affordances, not lessons.
const NON_LESSON_LETTER_CLASSES = new Set(["del", "space", "nothing"]);

const ASL_LETTERS = (letterClasses as string[]).filter((c) => !NON_LESSON_LETTER_CLASSES.has(c));

// Numbers and FSL letters come from ml/scripts/train_handshape_classifier.py.
// ASL numbers are 0-9; FSL-105, the only FSL numbers data, has one..ten and
// no zero, so FSL numbers are 1-10.
const ASL_NUMBERS = numberClasses as string[];
const FSL_LETTERS = fslLetterClasses as string[];
const FSL_NUMBERS = fslNumberClasses as string[];

/**
 * Words are listed alphabetically by the name the app shows (signNames.ts:
 * Tagalog for FSL, so "Abril, Agosto, alam, …"), ignoring case. Every list of
 * words in the classroom follows this order: the student's lessons, the
 * teacher's plan, module pickers and progress tables.
 */
function alphabetical(language: SignLanguage, signs: string[]): string[] {
  return [...signs].sort(
    (a, b) => signName(language, a).localeCompare(signName(language, b), "en", { sensitivity: "base" }) || a.localeCompare(b)
  );
}

/**
 * `signs` with the words the model recognises most reliably first
 * (wordPracticeOrder.json), alphabetical among unranked ones. Not a display
 * order: the class plan's starter uses it to pick the easiest words of each
 * category, so a new class starts with signs the computer checks well.
 */
export function mostReliableFirst(language: SignLanguage, signs: string[]): string[] {
  const rank = new Map((wordPracticeOrder[language] as string[]).map((sign, i) => [sign, i]));
  return alphabetical(language, signs).sort(
    (a, b) => (rank.get(a) ?? Number.MAX_SAFE_INTEGER) - (rank.get(b) ?? Number.MAX_SAFE_INTEGER)
  );
}

export const CURRICULUM: LanguageDefinition[] = [
  {
    language: "asl",
    label: "ASL",
    groups: [
      { group: "letters", label: "Letters", signs: ASL_LETTERS, available: true },
      { group: "numbers", label: "Numbers", signs: ASL_NUMBERS, available: true },
      {
        group: "words",
        label: "Words",
        signs: alphabetical("asl", (aslWordClasses as string[]).filter(notUnknown)),
        available: true,
      },
    ],
  },
  {
    language: "fsl",
    label: "FSL",
    groups: [
      { group: "letters", label: "Letters", signs: FSL_LETTERS, available: true },
      { group: "numbers", label: "Numbers", signs: FSL_NUMBERS, available: true },
      {
        group: "words",
        label: "Words",
        signs: alphabetical("fsl", (fslWordClasses as string[]).filter(notUnknown)),
        available: true,
      },
    ],
  },
];

export function getLanguage(language: SignLanguage): LanguageDefinition {
  return CURRICULUM.find((l) => l.language === language)!;
}

export function getGroup(language: SignLanguage, group: SignGroup): GroupDefinition {
  return getLanguage(language).groups.find((g) => g.group === group)!;
}

// ---- class learning plan ----

/**
 * A teacher's learning plan for one class (class_word_plans, 0012 + 0015):
 *  - per language, the words its Words group teaches; a language with no
 *    entry teaches every word;
 *  - `off`: whole groups the class doesn't learn (0015), e.g. a class that
 *    only does ASL, or skips numbers. An off group teaches nothing, so it
 *    is hidden from students and left out of every progress figure -
 *    otherwise a student who has learned everything their class teaches
 *    would still sit far below 100%. Letters and numbers are otherwise
 *    always the whole group.
 */
export type ClassPlan = Partial<Record<SignLanguage, string[]>> & {
  off?: Partial<Record<SignLanguage, SignGroup[]>>;
};

/** True when the class plan switches `group` off for `language`. */
export function groupOff(language: SignLanguage, group: SignGroup, plan?: ClassPlan | null): boolean {
  return !!plan?.off?.[language]?.includes(group);
}

/**
 * The signs a group teaches under `plan`, in curriculum order (words
 * alphabetical). Words the model no longer has are dropped, like moduleSigns().
 */
export function planSigns(language: SignLanguage, group: SignGroup, plan?: ClassPlan | null): string[] {
  if (groupOff(language, group, plan)) return [];
  const all = getGroup(language, group).signs;
  const chosen = group === "words" ? plan?.[language] : undefined;
  if (!chosen) return all;
  const keep = new Set(chosen);
  return all.filter((s) => keep.has(s));
}

/** A group students can learn in this class: it has a model and the plan gives it signs. */
export function groupInPlan(language: SignLanguage, group: SignGroup, plan?: ClassPlan | null): boolean {
  return getGroup(language, group).available && planSigns(language, group, plan).length > 0;
}

// ---- progress maths ----

export type GroupKey = `${SignLanguage}:${SignGroup}`;
export type MasteredCounts = Partial<Record<GroupKey, number>>;

export function groupKey(language: SignLanguage, group: SignGroup): GroupKey {
  return `${language}:${group}`;
}

/** The lesson_progress columns the maths below needs. */
export type ProgressRowLike = {
  language: string;
  sign_group: string;
  sign: string;
  passes: number;
};

export function isMastered(row: { passes: number } | null | undefined): boolean {
  return !!row && row.passes >= MASTERY_PASSES;
}

/**
 * Done in a teacher's module: passed since the module was made (`since` =
 * its created_at). A sign the student learned before doesn't count - the
 * teacher set the module, so the student still does it. Overall progress
 * (isMastered) keeps every pass. No `since` = any pass, like isMastered.
 * Both times are the database's now(), so the device clock doesn't matter.
 */
export function passedSince(
  row: { passes: number; last_passed_at?: string | null } | null | undefined,
  since: string | null | undefined
): boolean {
  if (!isMastered(row)) return false;
  if (!since) return true;
  const last = row!.last_passed_at ? Date.parse(row!.last_passed_at) : NaN;
  return Number.isFinite(last) && last >= Date.parse(since);
}

/**
 * Mastered signs per language+group. Only counts signs that are still in the
 * curriculum (and in the class plan, if there is one), so a row left over
 * from a renamed or dropped model class can't push a group past 100%.
 */
export function countMastered(rows: ProgressRowLike[], plan?: ClassPlan | null): MasteredCounts {
  const counts: MasteredCounts = {};
  for (const lang of CURRICULUM) {
    for (const g of lang.groups) {
      const signs = new Set(planSigns(lang.language, g.group, plan));
      const n = rows.filter(
        (r) =>
          r.language === lang.language && r.sign_group === g.group && signs.has(r.sign) && isMastered(r)
      ).length;
      counts[groupKey(lang.language, g.group)] = n;
    }
  }
  return counts;
}

export function groupFraction(
  language: SignLanguage,
  group: SignGroup,
  counts: MasteredCounts,
  plan?: ClassPlan | null
): number {
  const total = planSigns(language, group, plan).length;
  if (total === 0) return 0;
  return Math.min(1, (counts[groupKey(language, group)] ?? 0) / total);
}

/**
 * The one overall-progress figure, used by the student, teacher and admin
 * views alike. Two deliberate choices (docs/CLASSROOM_REDESIGN.md section 5):
 *  - Unavailable groups are left out entirely, so mastering every gradable
 *    sign reaches 100%. The denominator grows when a new model ships. So is
 *    a group the class plan switches off or leaves empty (a class that only
 *    learns ASL).
 *  - Each available group weighs the same (mean of group fractions), rather
 *    than pooling sign counts - pooled, 344 ASL words would drown out the
 *    26 letters and the bar would really be "percent of words".
 */
export function computeOverall(counts: MasteredCounts, plan?: ClassPlan | null): number {
  const fractions: number[] = [];
  for (const lang of CURRICULUM) {
    for (const g of lang.groups) {
      if (g.available && planSigns(lang.language, g.group, plan).length > 0) {
        fractions.push(groupFraction(lang.language, g.group, counts, plan));
      }
    }
  }
  if (fractions.length === 0) return 0;
  return fractions.reduce((a, b) => a + b, 0) / fractions.length;
}

export function formatPercent(fraction: number): string {
  return `${Math.round(fraction * 100)}%`;
}
